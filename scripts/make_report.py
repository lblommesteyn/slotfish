"""Render results/*.json into RESULTS_TABLES.md (numbers only; interpretation lives in RESULTS.md)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

R = Path(sys.argv[1] if len(sys.argv) > 1 else "results")


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def f(x, d=3):
    if x is None:
        return "n/a"
    if isinstance(x, (list, tuple)):
        return "[" + ", ".join(f(v, d) for v in x) + "]"
    if isinstance(x, float):
        return f"{x:.{d}f}"
    return str(x)


def table(rows: list[list], header: list[str]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(f(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    md = ["# Result tables\n", "Generated by `scripts/make_report.py` from `results/`.\n"]
    info = load(R / "info.json")
    if info:
        md.append("## Dataset\n")
        md.append(table([[k, json.dumps(v) if isinstance(v, dict) else v] for k, v in info.items()], ["field", "value"]))
    res = load(R / "research" / "research.json")
    if res:
        md.append("\n## Splits\n")
        md.append(table([[k, v] for k, v in res["bounds"].items()] + [["rows", res["split_rows"]]], ["split", "slots"]))
        for h, hr in res["horizons"].items():
            md.append(f"\n## Horizon {h}\n")
            if "skipped" in hr:
                md.append(f"skipped: {hr['skipped']} {hr['n']}\n")
                continue
            ls = hr["label_stats_train"]
            md.append(f"Train label (net executable return): n={ls['n']}, mean={f(ls['mean'])}, "
                      f"median={f(ls['median'])}, P(>0)={f(ls['p_pos'])}\n")
            rows = []
            for name, ev in hr["models"].items():
                tv = ev["test_at_val_threshold"]
                rows.append([name, ev.get("ic_spearman"), ev.get("ic_block_mean"), ev.get("ic_block_t"),
                             ev.get("auc_sign"), ev.get("top10_mean_ret"), ev.get("top10_ci95"),
                             ev.get("top1_mean_ret"), ev.get("top1_ci95"), ev["threshold"]["val_mean_ret"],
                             tv["n"], tv["mean_ret"], tv["ci95"]])
            md.append(table(rows, ["model", "test IC", "15m-block IC", "block t", "AUC", "top10% ret", "CI95",
                                   "top1% ret", "CI95", "val ret @thr", "test n @thr", "test ret @thr", "CI95"]))
            md.append("\n**Ablation (LightGBM, test):**\n")
            md.append(table([[k, v.get("ic_spearman"), v.get("ic_block_t"), v.get("top10_mean_ret"), v.get("top1_mean_ret")]
                             for k, v in hr["ablation"].items()], ["feature set", "IC", "block t", "top10% ret", "top1% ret"]))
            md.append("\n**Wallet increment (paired over 15-minute blocks):**\n")
            md.append(table([[k, v.get("mean_ic_diff"), v.get("t"), v.get("frac_blocks_positive"), v.get("blocks")]
                             for k, v in hr["wallet_increment"].items()], ["comparison", "mean IC diff", "t", "frac blocks >0", "blocks"]))
            md.append("\n**LightGBM gain share (top 10):**\n")
            md.append(table([[k, v] for k, v in list(hr["lgbm_gain"].items())[:10]], ["feature", "gain"]))
            cal = hr["models"]["lgbm"].get("calibration_test", [])
            if cal:
                md.append("\n**Calibration (LightGBM score deciles, test):**\n")
                md.append(table([[c["bin"], c["n"], c["pred"], c["realized"], c["hit"]] for c in cal],
                                ["decile", "n", "mean score", "realized ret", "hit"]))
    bt = load(R / "backtests.json")
    if bt:
        md.append("\n## Test-window backtests (event-driven engine, default execution)\n")
        cols = ["signals", "entered", "failed_entries", "slippage_rejects", "censored", "net_pnl_sol", "cost_sol",
                "mean_ret", "ret_t_stat", "hit_rate", "sharpe_15m_ann", "max_drawdown_sol", "turnover_sol", "exits_on_amm"]
        for h, rows in bt["results"].items():
            md.append(f"\n### Hold {h}\n")
            md.append(table([[k] + [v.get(c) for c in cols] for k, v in rows.items()], ["strategy"] + cols))
    for name in ("lgbm_2m", "momentum", "random"):
        p = R / f"sweep_{name}.jsonl"
        if p.exists():
            rows = [json.loads(l) for l in p.read_text().splitlines() if l.strip()]
            md.append(f"\n## Execution sensitivity: {name} (hold 120s)\n")
            md.append("Latency (slots) x p_fail at size 0.1 SOL:\n")
            md.append(table([[r["latency"], r["p_fail"], r["entered"], r["net_pnl_sol"], r["mean_ret"], r["ret_t_stat"]]
                             for r in rows if abs(r["size"] - 0.1) < 1e-9],
                            ["latency", "p_fail", "entered", "net SOL", "mean ret", "t"]))
            md.append("\nCapacity: size (SOL) at latency 2, p_fail 0.05:\n")
            md.append(table([[r["size"], r["entered"], r["net_pnl_sol"], r["mean_ret"], r["turnover_sol"]]
                             for r in rows if r["latency"] == 2 and abs(r["p_fail"] - 0.05) < 1e-9],
                            ["size", "entered", "net SOL", "mean ret", "turnover SOL"]))
    bench = load(R / "bench.json")
    if bench:
        md.append("\n## Benchmark\n")
        md.append("```json\n" + json.dumps(bench, indent=2) + "\n```")
    surv = load(R / "survival" / "survival.json")
    if surv:
        md.append(f"\n## Token survival (landmark {surv['landmark_s']}s, cohort {surv['cohort_tokens']})\n")
        for name, er in surv["endpoints"].items():
            md.append(f"\n### {name}: at risk {er['at_risk']}, events {er['events']}\n")
            md.append(table([[k, v] for k, v in er["km_cum_incidence"].items()], ["time after landmark", "KM cumulative incidence"]))
            if "cox" in er:
                md.append("\nCox PH (hazard ratio per SD):\n")
                md.append(table([[k, v["hr_per_sd"], v["p"]] for k, v in er["cox"].items()], ["covariate", "HR/SD", "p"]))
            c = er.get("classifier_10m")
            if c:
                md.append(f"\nActive tokens only (>=10 trades by landmark): AUC {f(c.get('auc_active_tokens'))}, "
                          f"n {c.get('active_test_n')}, event rate {f(c.get('active_test_rate'))}\n")
                md.append(f"\nClassifier, event within {surv['window_s']}s (chronological test): AUC {f(c['auc'])}, "
                          f"Brier {f(c['brier'], 4)} vs base-rate {f(c['brier_baseline'], 4)}, test rate {f(c['test_rate'])}\n")
                md.append(table([[x["pred"], x["obs"], x["n"]] for x in c["calibration"]], ["mean predicted", "observed", "n"]))
    paper = load(R / "paper.json")
    if paper:
        md.append("\n## Paper trading\n")
        md.append("```json\n" + json.dumps(paper, indent=2) + "\n```")
    (R.parent / "RESULTS_TABLES.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote", R.parent / "RESULTS_TABLES.md")


if __name__ == "__main__":
    main()
